package org.rsmod.content.areas.misc.stronghold

import org.rsmod.map.CoordGrid

/**
 * One half of a double door. The doors come in sets of two pairs three (once four) tiles apart
 * with a short safe corridor between them; the door leading OUT of that corridor is the one that
 * asks a security question. [airlockAcross] says whether the corridor lies on the far side of
 * this half's wall (true) or on the side of its own tile (false). [partnerX]/[partnerZ] is the
 * other half of the same pair, which opens together with it.
 *
 * Generated from the cache loc spawns of `loc.sos_*_door_face` / `_mirr` (280 halves).
 */
class Door(
    val level: Level,
    val x: Int,
    val z: Int,
    /** 0 = wall on the west edge of the tile, 1 north, 2 east, 3 south. */
    val angle: Int,
    val mirror: Boolean,
    val partnerX: Int,
    val partnerZ: Int,
    val airlockAcross: Boolean,
) {
    val tile: CoordGrid
        get() = CoordGrid(x, z)

    val partnerTile: CoordGrid
        get() = CoordGrid(partnerX, partnerZ)

    /** The tile on the far side of this half's wall. */
    val across: CoordGrid
        get() =
            when (angle) {
                0 -> CoordGrid(x - 1, z)
                1 -> CoordGrid(x, z + 1)
                2 -> CoordGrid(x + 1, z)
                else -> CoordGrid(x, z - 1)
            }

    /** Whether [coords] lies on the far side of this half's wall. */
    fun isAcross(coords: CoordGrid): Boolean =
        when (angle) {
            0 -> coords.x < x
            1 -> coords.z > z
            2 -> coords.x > x
            else -> coords.z < z
        }

    /** True when a player standing at [coords] is leaving the safe corridor through this door. */
    fun isExiting(coords: CoordGrid): Boolean = isAcross(coords) == airlockAcross

    /** The loc used while this half stands open. */
    val openLoc: String
        get() = if (mirror) level.doorMirrorOpen else level.doorFaceOpen
}

