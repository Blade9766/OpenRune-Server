/**
 * One-off generator for the pack's `halloween_decorations.txt`. For each town it reads the real map
 * collision, tile overlays and locs, then lays five passes over the outdoor tiles: lanterns around
 * landmarks (fountains, wells, statues, stalls), solid pieces against building walls where every
 * neighbouring path stays connected, lanterns across open plazas, pumpkin patches on natural ground
 * and walk-over fall leaves kept clear of walls and objects. Run with
 * `HALLOWEEN_DECOR_OUT=<path to halloween_decorations.txt>`.
 */
class DecorationPlacementGenerator {
    private data class Town(val key: String, val x1: Int, val z1: Int, val x2: Int, val z2: Int)

    private data class Placed(val x: Int, val z: Int, val shape: Int, val name: String)

    private data class Piece(val loc: String, val x: Int, val z: Int, val shape: Int, val angle: Int)

    @Test
    fun generate() {
        val out = System.getenv("HALLOWEEN_DECOR_OUT")
        assumeTrue(out != null)
        val cache = ServerCacheManager.init(241)
        val rows = StringBuilder()
        rows.appendLine("# town loc x z shape angle  (generated by DecorationPlacementGenerator)")
        val report = StringBuilder()
        for (town in TOWNS) {
            val collision = CollisionFlagMap()
            val placed = mutableListOf<Placed>()
            val paved = mutableSetOf<Long>()
            val squares = mutableSetOf<MapSquareKey>()
            for (x in town.x1 - 8..town.x2 + 8 step 8) for (z in town.z1 - 8..town.z2 + 8 step 8) {
                squares += MapSquareKey(x shr 6, z shr 6)
            }
            for (square in squares) {
                val group = (square.x shl 8) or square.z
                val tilesData = cache.data(MAPS, group, 0) ?: continue
                val locData = cache.data(MAPS, group, 1) ?: continue
                val tiles = MapTileDecoder.decode(InlineByteBuf(tilesData))
                val detail = MapTileDecoder.decode(Unpooled.wrappedBuffer(tilesData))
                for (grid in detail.overlays.keys) {
                    if (grid.level == 0) paved += key(square.x * 64 + grid.x, square.z * 64 + grid.z)
                }
                val spawns = MapLocListDecoder.decode(InlineByteBuf(locData))
                for (level in 0..3) for (x in square.x * 64 until square.x * 64 + 64 step 8) {
                    for (z in square.z * 64 until square.z * 64 + 64 step 8) {
                        collision.allocateIfAbsent(x, z, level)
                    }
                }
                val builder = GameMapBuilder()
                GameMapDecoder.putMaps(collision, square, tiles)
                GameMapDecoder.putLocs(builder, collision, square, tiles, spawns)
                for ((packed, zone) in builder.zoneBuilders) {
                    val base = ZoneKey(packed).toCoords()
                    if (base.level != 0) continue
                    for (entry in zone.build().byte2IntEntrySet()) {
                        val key = LocZoneKey(entry.byteKey)
                        val loc = LocEntity(entry.intValue)
                        val name = ServerCacheManager.getObject(loc.id)?.name?.lowercase() ?: ""
                        placed += Placed(base.x + key.x, base.z + key.z, loc.shape, name)
                    }
                }
            }
            val avoid = mutableSetOf<Long>()
            val occupied = mutableSetOf<Long>()
            val decorated = mutableSetOf<Long>()
            for (p in placed) {
                if (AVOID_WORDS.any { it in p.name }) {
                    for (dx in -2..2) for (dz in -2..2) avoid += key(p.x + dx, p.z + dz)
                }
                if (p.shape in 10..11) occupied += key(p.x, p.z)
                if (p.shape == GROUND_DECOR) decorated += key(p.x, p.z)
            }
            fun flag(x: Int, z: Int) = collision[x, z, 0]
            fun walkable(x: Int, z: Int) = flag(x, z) and BLOCKING == 0
            fun outdoors(x: Int, z: Int) = flag(x, z) and CollisionFlag.ROOF == 0
            fun inTown(x: Int, z: Int) = x in town.x1..town.x2 && z in town.z1..town.z2
            fun base(x: Int, z: Int) =
                inTown(x, z) && key(x, z) !in avoid && key(x, z) !in occupied && outdoors(x, z) &&
                    walkable(x, z)
            fun clearAround(x: Int, z: Int) =
                (-1..1).all { dx ->
                    (-1..1).all { dz ->
                        flag(x + dx, z + dz) and (WALLS or CollisionFlag.LOC) == 0 &&
                            outdoors(x + dx, z + dz)
                    }
                }
            fun open(x: Int, z: Int) = base(x, z) && flag(x, z) and WALLS == 0 && clearAround(x, z)
            fun clearOfLocs(x: Int, z: Int) =
                (-1..1).all { dx ->
                    (-1..1).all { dz ->
                        flag(x + dx, z + dz) and CollisionFlag.LOC == 0 && outdoors(x + dx, z + dz)
                    }
                }
            fun againstWall(x: Int, z: Int) =
                base(x, z) && flag(x, z) and WALLS == 0 && clearOfLocs(x, z) &&
                    listOf(x + 1 to z, x - 1 to z, x to z + 1, x to z - 1).any { (a, b) ->
                        flag(a, b) and WALLS != 0
                    }
            fun plaza(x: Int, z: Int) =
                (-2..2).sumOf { dx ->
                    (-2..2).count { dz -> walkable(x + dx, z + dz) && outdoors(x + dx, z + dz) }
                } >= PLAZA_TILES
            fun keepsConnected(x: Int, z: Int): Boolean {
                val ring =
                    listOf(x + 1 to z, x - 1 to z, x to z + 1, x to z - 1).filter { (a, b) ->
                        walkable(a, b)
                    }
                if (ring.size <= 1) return ring.size == 1
                val seen = mutableSetOf(ring.first())
                val queue = ArrayDeque(listOf(ring.first()))
                while (queue.isNotEmpty()) {
                    val (a, b) = queue.removeFirst()
                    for ((na, nb) in listOf(a + 1 to b, a - 1 to b, a to b + 1, a to b - 1)) {
                        if (na == x && nb == z) continue
                        if (abs(na - x) > 3 || abs(nb - z) > 3) continue
                        if (!walkable(na, nb) || !seen.add(na to nb)) continue
                        queue += na to nb
                    }
                }
                return ring.all { it in seen }
            }

            val random = Random(town.key.hashCode())
            val all = (town.x1..town.x2).flatMap { x -> (town.z1..town.z2).map { z -> x to z } }
            val area = all.count { (x, z) -> base(x, z) }
            val pieces = mutableListOf<Piece>()
            val used = mutableSetOf<Long>()
            fun near(x: Int, z: Int, spacing: Int, shape: Int) =
                pieces.any { it.shape == shape && max(abs(it.x - x), abs(it.z - z)) < spacing }
            fun put(loc: String, x: Int, z: Int, shape: Int) {
                pieces += Piece(loc, x, z, shape, random.nextInt(4))
                used += key(x, z)
            }
            fun free(x: Int, z: Int) = key(x, z) !in used
            fun bare(x: Int, z: Int) = free(x, z) && key(x, z) !in decorated

            var landmarkLights = 0
            val landmarks =
                placed.filter { p -> inTown(p.x, p.z) && LANDMARK_WORDS.any { it in p.name } }
            for (mark in landmarks.shuffled(random)) {
                val ring =
                    (-3..3).flatMap { dx -> (-3..3).map { dz -> mark.x + dx to mark.z + dz } }
                        .filter { (x, z) -> max(abs(x - mark.x), abs(z - mark.z)) in 2..3 }
                        .filter { (x, z) -> open(x, z) && free(x, z) }
                        .shuffled(random)
                var lit = 0
                for ((x, z) in ring) {
                    if (lit >= LANDMARK_LIGHTS || near(x, z, 2, CENTREPIECE)) continue
                    val big = plaza(x, z) && keepsConnected(x, z) && random.nextInt(2) == 0
                    put(if (big) PLAZA_SOLID.random(random) else LIGHT.random(random), x, z, CENTREPIECE)
                    lit++
                }
                landmarkLights += lit
                val litter =
                    (-4..4).flatMap { dx -> (-4..4).map { dz -> mark.x + dx to mark.z + dz } }
                        .filter { (x, z) -> open(x, z) && bare(x, z) }
                        .shuffled(random)
                var fallen = 0
                for ((x, z) in litter) {
                    if (fallen >= LANDMARK_LEAVES || near(x, z, LEAF_SPACING, GROUND_DECOR)) continue
                    put(LEAVES.random(random), x, z, GROUND_DECOR)
                    fallen++
                }
            }

            val solidCount = (area / SOLID_PER).coerceIn(4, 25)
            var solids = 0
            for ((x, z) in all.shuffled(random)) {
                if (solids >= solidCount) break
                if (!againstWall(x, z) || !free(x, z)) continue
                if (near(x, z, SOLID_SPACING, CENTREPIECE) || !keepsConnected(x, z)) continue
                put(SOLID.random(random), x, z, CENTREPIECE)
                solids++
            }

            val lightCount = (area / LIGHT_PER).coerceIn(6, 35)
            var lights = 0
            val lightTiles =
                all.filter { (x, z) -> open(x, z) }
                    .shuffled(random)
                    .sortedByDescending { (x, z) -> plaza(x, z) }
            for ((x, z) in lightTiles) {
                if (lights >= lightCount) break
                if (!free(x, z) || near(x, z, LIGHT_SPACING, CENTREPIECE)) continue
                put(LIGHT.random(random), x, z, CENTREPIECE)
                lights++
            }

            val patchCount = (area / PATCH_PER).coerceIn(3, 18)
            var patches = 0
            val natural = all.filter { (x, z) -> open(x, z) && key(x, z) !in paved }.shuffled(random)
            for ((x, z) in natural) {
                if (patches >= patchCount) break
                if (!free(x, z) || near(x, z, PATCH_SPACING, CENTREPIECE)) continue
                val colour = PUMPKINS.random(random)
                val cluster = mutableListOf(x to z)
                for ((dx, dz) in listOf(1 to 0, 0 to 1, -1 to 0, 0 to -1, 1 to 1).shuffled(random)) {
                    if (cluster.size >= 2 + random.nextInt(2)) break
                    val nx = x + dx
                    val nz = z + dz
                    if (open(nx, nz) && free(nx, nz) && key(nx, nz) !in paved) cluster += nx to nz
                }
                if (cluster.size < 2) continue
                for ((cx, cz) in cluster) put(colour, cx, cz, CENTREPIECE)
                patches++
            }

            val leafCount = (area / LEAF_PER).coerceIn(30, 220)
            var leaves = 0
            val leafTiles =
                all.filter { (x, z) -> open(x, z) }
                    .map { (x, z) -> Triple(x, z, key(x, z) !in paved && random.nextInt(4) != 0) }
                    .shuffled(random)
                    .sortedByDescending { it.third }
                    .map { (x, z) -> x to z }
            for ((x, z) in leafTiles) {
                if (leaves >= leafCount) break
                if (!bare(x, z) || near(x, z, LEAF_SPACING, GROUND_DECOR)) continue
                put(LEAVES.random(random), x, z, GROUND_DECOR)
                leaves++
            }

            report.appendLine(
                "${town.key}: area=$area landmarks=${landmarks.size}/$landmarkLights " +
                    "solids=$solids lights=$lights patches=$patches leaves=$leaves",
            )
            for (p in pieces) {
                rows.appendLine("${town.key} ${p.loc} ${p.x} ${p.z} ${p.shape} ${p.angle}")
            }
        }
        File(out!!).writeText(rows.toString())
        println(report)
        cache.close()
    }

