    private val bySeed: Map<String, Crop> = ALL.associateBy(Crop::seed)
    private val byKey: Map<String, Crop> = ALL.associateBy(Crop::key)

    fun forSeed(seed: String): Crop? = bySeed[seed]

    fun forKey(key: String): Crop? = byKey[key]

    fun of(kind: PatchKind): List<Crop> = ALL.filter { it.kind == kind }

    private fun allotment(
        key: String,
        seed: String,
        produce: String,
        level: Int,
        plantXp: Double,
        harvestXp: Double,
        growthMinutes: Int,
        growth: IntArray,
        watered: IntArray,
        diseased: IntArray,
        dead: IntArray,
        protection: Protection,
    ) = Crop(
        key = key,
        kind = PatchKind.ALLOTMENT,
        seed = seed,
        produce = produce,
        level = level,
        plantXp = plantXp,
        harvestXp = harvestXp,
        growthMinutes = growthMinutes,
        seedsPerPlant = 3,
        growth = growth,
        watered = watered,
        diseased = diseased,
        dead = dead,
        protection = protection,
        lives = 3,
        diseaseChance = ALLOTMENT_DISEASE,
    )

    private fun herb(
        key: String,
        seed: String,
        produce: String,
        level: Int,
        plantXp: Double,
        harvestXp: Double,
        growthBase: Int,
        diseasedBase: Int,
    ) = Crop(
        key = key,
        kind = PatchKind.HERB,
        seed = seed,
        produce = produce,
        level = level,
        plantXp = plantXp,
        harvestXp = harvestXp,
        growthMinutes = 80,
        seedsPerPlant = 1,
        growth = states(growthBase, 5),
        watered = NO_WATER,
        diseased = states(diseasedBase, 3),
        dead = states(HERB_DEAD_BASE, 3),
        protection = null,
        lives = 3,
        diseaseChance = HERB_DISEASE,
    )

