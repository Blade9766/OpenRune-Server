    private const val HERB_DEAD_BASE = 170

    /**
     * Disease chance per growth cycle, out of 128 and before compost. Jagex has never published the
     * per-crop numbers; these follow the ordering the wiki does state - hops are more susceptible
     * than herbs but hardier than allotments - and flowers, which players rarely lose, sit lowest.
     */
    private const val ALLOTMENT_DISEASE = 25
    private const val HOPS_DISEASE = 20
    private const val HERB_DISEASE = 16
    private const val FLOWER_DISEASE = 13
}
